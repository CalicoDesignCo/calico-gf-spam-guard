<?php
ob_start(); require __DIR__ . '/admin-render.php'; ob_end_clean();
$mail = array();
$mail_ok = true;
function wp_mail( $to, $subject, $body, $headers = array() ) { global $mail, $mail_ok; $mail[] = compact( 'to', 'subject', 'body', 'headers' ); return $mail_ok; }
$settings = array( 'enabled' => true, 'test_mode' => false, 'alert_enabled' => true, 'alert_recipients' => array( 'one@example.com', 'two@example.com' ), 'rules' => array( rule( 'contains', array( 'spam', 'not-matched' ), array( 'label' => 'Solicitation terms' ) ) ) );
$options[CGSG_Plugin::OPTION] = $settings;
$form = GFAPI::get_form( 1 );
$entry = array( 'id' => 123, 'status' => 'spam', 1 => 'visitor@example.com', 2 => "Original spam message\nSecond line <a href=\"https://example.test\">raw link</a>", 4 => 'PASSWORD-SECRET', 6 => 'HIDDEN-SECRET' );
$plugin = new CGSG_Plugin();
expect( $hooks['gform_after_submission'][1] === 2, 'alert runs after saved submission' );
$plugin->check_spam( false, $form, $entry );
expect( count( $mail ) === 0, 'no alert sent during spam evaluation' );
$plugin->quarantine_alert( $entry, $form );
expect( count( $mail ) === 1, 'saved spam triggers alert' );
expect( $mail[0]['to'] === $settings['alert_recipients'], 'both configured recipients used' );
expect( strpos( $mail[0]['subject'], '[Quarantined]' ) === 0, 'subject clearly identifies quarantine' );
expect( strpos( $mail[0]['body'], $entry[2] ) !== false, 'original multiline message preserved verbatim' );
expect( strpos( $mail[0]['body'], 'visitor@example.com' ) !== false, 'submitted email included' );
expect( strpos( $mail[0]['body'], 'Solicitation terms: Text contains matched spam' ) !== false, 'specific rule and matching term explained' );
expect( strpos( $mail[0]['body'], 'not-matched' ) === false, 'nonmatching rule value omitted from reason' );
expect( strpos( $mail[0]['body'], 'PASSWORD-SECRET' ) === false && strpos( $mail[0]['body'], 'HIDDEN-SECRET' ) === false, 'secrets omitted' );
expect( strpos( $mail[0]['body'], 'lid=123' ) !== false, 'entry review link included' );
expect( $mail[0]['headers'] === array( 'Content-Type: text/plain; charset=UTF-8' ), 'plain text mail header' );
expect( $plugin->activity()[0]['alert'] === 'Alert accepted by mail system', 'mail acceptance recorded accurately' );
$plugin->quarantine_alert( $entry, $form );
expect( count( $mail ) === 1, 'duplicate action does not duplicate alert' );
$plugin = new CGSG_Plugin();
$active = $entry; $active['status'] = 'active';
$plugin->check_spam( false, $form, $entry );
$plugin->quarantine_alert( $active, $form );
expect( count( $mail ) === 1, 'entry must actually be spam' );
$different = $entry; $different['id'] = 124;
$plugin->quarantine_alert( $different, $form );
expect( count( $mail ) === 1, 'alert cannot be associated with a different entry' );
$plugin = new CGSG_Plugin();
$options[CGSG_Plugin::OPTION]['test_mode'] = true;
$plugin->check_spam( false, $form, $entry ); $plugin->quarantine_alert( $entry, $form );
expect( count( $mail ) === 1, 'test mode sends no alert' );
$plugin = new CGSG_Plugin();
$options[CGSG_Plugin::OPTION] = $settings;
$plugin->check_spam( true, $form, $entry ); $plugin->quarantine_alert( $entry, $form );
expect( count( $mail ) === 1, 'other spam provider alone sends no alert' );
$plugin = new CGSG_Plugin();
$options[CGSG_Plugin::OPTION]['alert_enabled'] = false;
$plugin->check_spam( false, $form, $entry ); $plugin->quarantine_alert( $entry, $form );
expect( count( $mail ) === 1, 'disabled alerts send no mail' );
$plugin = new CGSG_Plugin();
$options[CGSG_Plugin::OPTION] = $settings;
$mail_ok = false;
$plugin->check_spam( false, $form, $entry ); $plugin->quarantine_alert( $entry, $form );
expect( strpos( $plugin->activity()[0]['alert'], 'Alert failed' ) === 0, 'mail failure recorded' );
expect( $plugin->disable_notification( false, array(), $form, $entry ), 'normal notifications still suppressed with alerts enabled' );
expect( strpos( serialize( $plugin->activity() ), 'Original spam message' ) === false, 'alert body not copied into log' );
$plugin = new CGSG_Plugin();
$mail_ok = true;
$pre_save = $entry; unset( $pre_save['id'], $pre_save['status'] );
$plugin->check_spam( false, $form, $pre_save ); $plugin->quarantine_alert( $entry, $form );
expect( count( $mail ) === 3, 'pre-save evaluation associates by field fingerprint' );
